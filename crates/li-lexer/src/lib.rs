//! li 语言的词法分析器。
//!
//! # 归一化规则
//!
//! 词法分析阶段直接消除全角与半角的书写差异：
//! - 标点：`（` 与 `(`、`；` 与 `;`、`＝` 与 `=` 等产生相同 Token；
//! - 关键字：中文关键字与英文别名产生相同 Token，例如 `函数` 与 `fn`；
//! - 运算符：`加` 与 `+`、`等于` 与 `==` 等产生相同 Token。
//!
//! 字符串只接受 `「」` 定界符。注释支持 `#`、`//` 单行形式，
//! 以及可嵌套的 `#* ... *#`、`/* ... */` 多行形式。
//!
//! 词法错误通过 [`li_errors::DiagnosticBag`] 返回，全部为带行列号的中文信息。

mod lexer;
mod token;

pub use lexer::{lex, Lexer};
pub use token::{Token, TokenKind};
